import { z } from 'zod';

/**
 * UUIDv7 (RFC 9562): 48-bit Unix ms timestamp + random bits.
 * Time-ordered, so client-generated IDs sort roughly by creation time,
 * and collision-resistant enough to be used as an idempotency key.
 */
export function uuidv7(now: number = Date.now()): string {
  const bytes = new Uint8Array(16);
  globalThis.crypto.getRandomValues(bytes);
  const ts = BigInt(now);
  bytes[0] = Number((ts >> 40n) & 0xffn);
  bytes[1] = Number((ts >> 32n) & 0xffn);
  bytes[2] = Number((ts >> 24n) & 0xffn);
  bytes[3] = Number((ts >> 16n) & 0xffn);
  bytes[4] = Number((ts >> 8n) & 0xffn);
  bytes[5] = Number(ts & 0xffn);
  bytes[6] = (bytes[6]! & 0x0f) | 0x70; // version 7
  bytes[8] = (bytes[8]! & 0x3f) | 0x80; // RFC 4122 variant
  const hex = Array.from(bytes, (b) => b.toString(16).padStart(2, '0')).join('');
  return `${hex.slice(0, 8)}-${hex.slice(8, 12)}-${hex.slice(12, 16)}-${hex.slice(16, 20)}-${hex.slice(20)}`;
}

const UUID_RE = /^[0-9a-f]{8}-[0-9a-f]{4}-[1-8][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/i;

/** Client-generated identifiers (clientMessageId, deviceId) must be UUIDs. */
export const ClientIdSchema = z.string().regex(UUID_RE, 'must be a UUID');

/** Server identifiers are opaque strings (MongoDB ObjectId hex today). */
export const ServerIdSchema = z.string().min(1).max(64);
