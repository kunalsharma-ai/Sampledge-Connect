import { DEFAULT_THEME, getTheme, THEMES, themeToCssVars, type Theme } from './themes.js';
import { fonts, layout, motion, radii, typeScale } from './scales.js';

function block(selector: string, vars: Record<string, string>): string {
  const body = Object.entries(vars)
    .map(([k, v]) => `  ${k}: ${v};`)
    .join('\n');
  return `${selector} {\n${body}\n}`;
}

function themeVars(theme: Theme): Record<string, string> {
  const c = theme.colors;
  return {
    'color-scheme': theme.mode,
    ...themeToCssVars(theme),
    '--sc-shadow-sm': `0 1px 2px ${c.shadowColor}1F`,
    '--sc-shadow-md':
      theme.mode === 'dark'
        ? `0 1px 0 0 rgb(255 255 255 / 4%) inset, 0 8px 24px -8px ${c.shadowColor}99`
        : `0 1px 2px ${c.shadowColor}14, 0 8px 24px -12px ${c.shadowColor}29`,
    '--sc-shadow-lg':
      theme.mode === 'dark'
        ? `0 1px 0 0 rgb(255 255 255 / 5%) inset, 0 24px 48px -16px ${c.shadowColor}B3`
        : `0 2px 4px ${c.shadowColor}0F, 0 24px 48px -20px ${c.shadowColor}40`,
  };
}

/** Generates the stylesheet shipped as `@sampledge/design-tokens/themes.css`. */
export function buildThemesCss(): string {
  const shared: Record<string, string> = {
    '--sc-font-sans': fonts.sans,
    '--sc-font-display': fonts.display,
    '--sc-font-mono': fonts.mono,
  };
  for (const [k, v] of Object.entries(radii)) shared[`--sc-radius-${k}`] = v;
  for (const [k, v] of Object.entries(layout))
    shared[`--sc-layout-${k.replace(/[A-Z]/g, (m) => `-${m.toLowerCase()}`)}`] = v;
  for (const [k, v] of Object.entries(motion.duration)) shared[`--sc-duration-${k}`] = `${v}ms`;
  for (const [k, v] of Object.entries(motion.easing))
    shared[`--sc-ease-${k}`] = `cubic-bezier(${v.join(', ')})`;
  for (const [k, [size, lh, ls, w]] of Object.entries(typeScale)) {
    shared[`--sc-text-${k}`] = size;
    shared[`--sc-text-${k}-lh`] = lh;
    shared[`--sc-text-${k}-ls`] = ls;
    shared[`--sc-text-${k}-weight`] = w;
  }

  const parts = [
    '/* Generated by @sampledge/design-tokens. Do not edit. */',
    block(':root', shared),
    block(`:root, [data-theme="${DEFAULT_THEME}"]`, themeVars(THEMES[DEFAULT_THEME])),
  ];
  for (const theme of Object.values(THEMES)) {
    if (theme.id === DEFAULT_THEME) continue;
    parts.push(block(`[data-theme="${theme.id}"]`, themeVars(theme)));
  }
  // Fallback brand theme; real tenant colors are applied at runtime as inline vars.
  parts.push(block('[data-theme="custom-brand"]', themeVars(getTheme('custom-brand'))));
  parts.push(
    `@media (prefers-reduced-motion: reduce) {\n${block(':root', Object.fromEntries(Object.keys(motion.duration).map((k) => [`--sc-duration-${k}`, '1ms'])))}\n}`,
  );
  return parts.join('\n\n') + '\n';
}
